import {chromium, expect} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {emptyWorkspace,transition} from '../src/workspace-model.js';
const state=transition(emptyWorkspace(),{type:'add-loadout',id:'programming-review',name:'Programming Review',venueId:'room'},[{id:'room',name:'Room',assetUrl:'/scan.ply',status:'ready',setupStatus:'configured'}]);
state.units=Array.from({length:4},(_,i)=>({id:'wash-'+i,name:'Wash '+(i+1),role:'Wash',model:'RGB Wash',footprint:8}));
state.loadouts[0].extraUnitIds=state.units.map(f=>f.id);
const browser=await chromium.launch({headless:true,executablePath:process.env.VV_CHROMIUM_EXECUTABLE||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const page=await browser.newPage({viewport:{width:1500,height:1100}});
page.setDefaultTimeout(15000);
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const output=new URL('../../../tmp/programming-workflow/',import.meta.url).pathname;
await mkdir(output,{recursive:true});
try {
 await page.addInitScript(s=>localStorage.setItem('vv-workspace-v2',JSON.stringify(s)),state);
 await page.goto(`${process.env.VV_BASE_URL||'http://127.0.0.1:5174'}/?screen=preset-editor&loadoutId=programming-review`);
 await page.locator('.palette-pool-cell').filter({hasText:'Dimmer chase'}).click();
 await expect(page.getByRole('button',{name:'120',exact:true})).toHaveCount(0);
 const before=await page.getByLabel('Beats per cycle',{exact:true}).inputValue();
 await page.getByLabel('Step count',{exact:true}).fill('8');
 await expect(page.getByLabel('Beats per cycle',{exact:true})).toHaveValue(before);
 await page.getByRole('button',{name:'2 bars',exact:true}).click();
 await expect(page.getByLabel('Beats per cycle',{exact:true})).toHaveValue('8');
 await page.getByRole('button',{name:'Select step 3',exact:true}).click();
 await page.getByLabel('Step source',{exact:true}).selectOption('Intensity · Full');
 await page.getByLabel('Transition into step (%)',{exact:true}).fill('50');
 await page.getByRole('button',{name:'Update palette',exact:true}).click();
 await page.getByRole('button',{name:'Wash',exact:true}).click();
 await page.getByText('Macros · repeat a palette workflow',{exact:true}).click();
 const macro=page.locator('.macro-workbench');
 await expect(macro.getByRole('button',{name:'Run macro',exact:true})).toBeEnabled();
 await macro.getByRole('button',{name:'Run macro',exact:true}).click();
 await expect(macro.getByText('Applied 2 actions to 4 fixtures.',{exact:true})).toBeVisible();
 await macro.getByRole('button',{name:'Undo macro',exact:true}).click();
 await expect(macro.getByText('Undid the whole macro run.',{exact:true})).toBeVisible();
 await macro.getByRole('button',{name:'Add action',exact:true}).click();
 await expect(macro.getByRole('button',{name:'Run macro',exact:true})).toBeDisabled();
 await macro.getByLabel('Apply saved palette').last().selectOption('Color · Blue');
 await macro.getByRole('button',{name:'Store macro',exact:true}).click();
 await expect(macro.getByText('Stored macro.',{exact:true})).toBeVisible();
 await page.reload();
 await page.getByText('Macros · repeat a palette workflow',{exact:true}).click();
 await expect(page.locator('.macro-line')).toHaveCount(3);
 await page.getByRole('button',{name:'Clear selection',exact:true}).click();
 await expect(macro.getByRole('button',{name:'Run macro',exact:true})).toBeDisabled();
 await page.getByRole('button',{name:'Wash',exact:true}).click();
 await page.getByText('Macros · repeat a palette workflow',{exact:true}).click();
 await page.locator('.palette-pool-cell').filter({hasText:'Dimmer chase'}).click();
 await page.getByRole('region',{name:'Palette programmer'}).screenshot({path:output+'saas-editor.png'});
 await page.setViewportSize({width:700,height:1000});
 await expect(page.getByLabel('Step count',{exact:true})).toBeVisible();
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'No narrow viewport overflow');
 await page.screenshot({path:output+'saas-narrow.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('Programming browser checks passed: independent timing, linked sources, macro run/undo, dirty and empty-selection guards, persisted macros, narrow layout.');
} catch(error) { await page.screenshot({path:output+'failure.png',fullPage:true});console.log((await page.locator('body').innerText()).slice(-6000));throw error; } finally {await browser.close();}
