async function drag(from, to, cancel = false, outside = false) {
  const handle = page.locator(`[data-script-entry="${from}"] .slot-grip`);
  await handle.scrollIntoViewIfNeeded();
  const source = await handle.boundingBox();
  const target = await page.locator(`[data-script-entry="${to}"]`).boundingBox();
  await page.mouse.move(source.x + source.width / 2, source.y + source.height / 2);
  await page.mouse.down();
  await page.mouse.move(target.x + 30, target.y + target.height / 2, { steps: 12 });
  await expect(page.locator(`[data-script-entry="${to}"]`)).toHaveClass(/drop-target/);
  if (cancel) await page.keyboard.press("Escape");
  if (outside) await page.mouse.move(15, 15);
  await page.mouse.up();
}
